#!/usr/bin/env node
/**
 * Turns the SVG files in src/icons/svg into src/icons/registry.ts.
 *
 *   npm run icons                      (reads src/icons/svg, writes src/icons/registry.ts)
 *   node scripts/build-icons.mjs <dir> <out.ts>
 *
 * Made for Figma exports: it drops width/height, turns every fill and stroke colour into currentColor
 * (so icons follow the text colour and the theme), keeps fill="none" on the root, prefixes ids so two
 * icons never clash, and refuses anything that could run code.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = path.resolve(process.argv[2] ?? path.join(root, "src/icons/svg"));
const outFile = path.resolve(process.argv[3] ?? path.join(root, "src/icons/registry.ts"));

const toName = (file) =>
  file.replace(/\.svg$/i, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

function convert(file, source) {
  if (/<script|<foreignObject|\son[a-z]+\s*=|javascript:/i.test(source)) {
    throw new Error(`${file}: contains script-like content, refusing to import`);
  }
  const m = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>/i);
  if (!m) throw new Error(`${file}: no <svg> element found`);
  const [, attrs, inner] = m;

  let viewBox = attrs.match(/viewBox\s*=\s*"([^"]+)"/i)?.[1];
  if (!viewBox) {
    const w = attrs.match(/\bwidth\s*=\s*"([\d.]+)/i)?.[1];
    const h = attrs.match(/\bheight\s*=\s*"([\d.]+)/i)?.[1];
    if (!w || !h) throw new Error(`${file}: needs a viewBox (or width and height)`);
    viewBox = `0 0 ${w} ${h}`;
  }
  const fill = /\sfill\s*=\s*"none"/i.test(attrs) ? "none" : "currentColor";

  let body = inner
    .replace(/<!--[\s\S]*?-->/g, "")
    .replace(/<(title|desc)\b[\s\S]*?<\/\1>/gi, "")
    .replace(/\s(fill|stroke)\s*=\s*"(?!none\b|currentColor\b|url\()[^"]*"/gi, ' $1="currentColor"')
    .replace(/>\s+</g, "><")
    .trim();

  if (/\sstyle\s*=/i.test(body)) console.warn(`  ! ${file}: has inline style, colours in it are not converted`);
  if (/<(linearGradient|radialGradient|mask|filter|image)\b/i.test(body)) {
    console.warn(`  ! ${file}: gradients, masks, filters and images do not follow the theme. Flatten it in Figma.`);
  }

  // Figma writes ids like clip0_12_34. Prefix them so inlined icons never share an id.
  const prefix = `i-${toName(file)}-`;
  for (const id of new Set([...body.matchAll(/\sid\s*=\s*"([^"]+)"/g)].map((x) => x[1]))) {
    const esc = id.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    body = body
      .replace(new RegExp(`(\\sid\\s*=\\s*")${esc}"`, "g"), `$1${prefix}${id}"`)
      .replace(new RegExp(`url\\(#${esc}\\)`, "g"), `url(#${prefix}${id})`)
      .replace(new RegExp(`((?:xlink:)?href\\s*=\\s*")#${esc}"`, "g"), `$1#${prefix}${id}"`);
  }
  return { viewBox, fill, body };
}

const files = (await readdir(srcDir)).filter((f) => /\.svg$/i.test(f)).sort();
const icons = {};
for (const file of files) {
  const name = toName(file);
  if (!name) throw new Error(`${file}: the file name has no letters or digits`);
  if (icons[name]) throw new Error(`${file}: duplicate icon name "${name}"`);
  icons[name] = convert(file, await readFile(path.join(srcDir, file), "utf8"));
}

const lines = Object.entries(icons).map(([name, d]) => `  ${JSON.stringify(name)}: ${JSON.stringify(d)},`);
const ts = `// GENERATED by scripts/build-icons.mjs from src/icons/svg. Do not edit by hand: run \`npm run icons\`.

export interface IconData {
  viewBox: string;
  fill: "none" | "currentColor";
  body: string;
}

export const icons = {
${lines.join("\n")}
} satisfies Record<string, IconData>;

export type IconName = keyof typeof icons;
`;
await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, ts);
console.log(`${files.length} icons -> ${path.relative(root, outFile)}`);
